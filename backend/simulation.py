"""Stateful demo library seats. Never fabricates Arduino sensor readings.

One physical seat A01 is supplied separately by the serial gateway.
All other seats have source SIMULATED and their own timed state machine.
"""
from __future__ import annotations
from dataclasses import dataclass

import random

FLOORS = (
    ("F1", "Floor 1", "Reading Area"),
    ("F2", "Floor 2", "Group Study"),
    ("F3", "Floor 3", "Silent Zone"),
)
SCENARIOS = ("NORMAL", "PEAK", "LOW", "ALERTS")


@dataclass
class VirtualSeat:
    seat_id: str
    floor_id: str
    physical: str = "FREE"
    locked: bool = False
    armed: bool = True
    away_ms: int = 0
    phase_age: float = 0.0
    next_transition: float = 45.0
    last_action: str = "INIT"

    @property
    def effective(self) -> str:
        return "LOCKED" if self.locked else self.physical

    def as_dict(self) -> dict:
        return {
            "id": self.seat_id, "floor_id": self.floor_id,
            "source": "SIMULATED", "online": True,
            "physical": self.physical, "state": self.effective,
            "locked": self.locked, "available": self.physical == "FREE" and not self.locked,
            "away_ms": int(self.away_ms), "last_action": self.last_action,
        }


class SimulationEngine:
    def __init__(self) -> None:
        self.rng = random.Random(20261110)
        self.scenario = "NORMAL"
        self.speed = 1
        self.running = True
        self.elapsed = 0.0
        self.seats: dict[str, VirtualSeat] = {}
        self.reset()

    def reset(self) -> None:
        self.elapsed = 0.0
        self.seats.clear()
        for floor_id, _, _ in FLOORS:
            for n in range(1, 21):
                if floor_id == "F1" and n == 1:  # reserved for physical Arduino A01
                    continue
                s = VirtualSeat(f"{floor_id}-{n:02d}", floor_id)
                # Realistic varied initial conditions, generated by the simulation seed.
                p = self.rng.random()
                s.physical = "IN_USE" if p < 0.57 else "AWAY" if p < 0.64 else "FREE"
                s.phase_age = self.rng.uniform(0, 6) if s.physical == "AWAY" else 0.0
                s.away_ms = int(s.phase_age * 1000) if s.physical == "AWAY" else 0
                s.next_transition = self._duration(s)
                self.seats[s.seat_id] = s

    def _duration(self, s: VirtualSeat) -> float:
        if s.physical == "IN_USE":
            return self.rng.uniform(25, 95)
        if s.physical == "AWAY":
            return self.rng.uniform(6, 13)
        return self.rng.uniform(15, 75)

    def _target(self, s: VirtualSeat) -> str:
        # The scenario alters transition probabilities, never hardware readings.
        occupied_probability = {"NORMAL": .65, "PEAK": .93, "LOW": .14, "ALERTS": .78}[self.scenario]
        if s.physical == "FREE":
            return "IN_USE" if self.rng.random() < occupied_probability else "FREE"
        if s.physical == "IN_USE":
            r = self.rng.random()
            if self.scenario == "ALERTS":
                return "AWAY" if r < .78 else "FREE"
            return "AWAY" if r < .28 else "FREE" if r < .63 else "IN_USE"
        if s.physical == "AWAY":
            if self.scenario == "ALERTS":
                return "AWAY" if self.rng.random() < .87 else "IN_USE"
            return "IN_USE" if self.rng.random() < occupied_probability else "FREE"
        return "FREE"

    def tick(self, seconds: float) -> list[dict]:
        if not self.running:
            return []
        dt = min(max(seconds, 0.0), 10.0) * self.speed
        self.elapsed += dt
        changed = []
        for s in self.seats.values():
            old = s.effective
            s.phase_age += dt
            if s.physical == "AWAY":
                s.away_ms += int(dt * 1000)
                if not s.locked and s.armed and s.away_ms >= 10000:
                    s.locked = True
                    s.armed = False
                    s.last_action = "AWAY_TIMEOUT"
            if s.phase_age >= s.next_transition:
                nxt = self._target(s)
                if nxt != s.physical:
                    s.physical = nxt
                    s.last_action = "SIM_STATE_CHANGE"
                    if nxt in ("FREE", "IN_USE"):
                        s.away_ms = 0
                        s.armed = True if not s.locked else False
                    else:
                        s.away_ms = 0
                s.phase_age = 0
                s.next_transition = self._duration(s)
            if s.effective != old:
                changed.append({"id": s.seat_id, "from": old, "to": s.effective, "source": "SIMULATED"})
        return changed

    def release(self, seat_id: str) -> bool:
        s = self.seats.get(seat_id)
        if s is None or not s.locked:
            return False
        s.locked = False
        s.armed = s.physical in ("FREE", "IN_USE")
        s.last_action = "ADMIN_RELEASE"
        return True

    def control(self, *, scenario: str | None = None, speed: int | None = None,
                running: bool | None = None, reset: bool = False) -> None:
        if scenario is not None:
            if scenario not in SCENARIOS:
                raise ValueError("Invalid scenario")
            self.scenario = scenario
        if speed is not None:
            if speed not in (1, 5, 10):
                raise ValueError("Speed must be 1, 5, or 10")
            self.speed = speed
        if running is not None:
            self.running = running
        if reset:
            self.reset()

    def as_dict(self) -> dict:
        return {"scenario": self.scenario, "speed": self.speed,
                "running": self.running, "elapsed_s": round(self.elapsed, 1),
                "simulated_seat_count": len(self.seats)}
